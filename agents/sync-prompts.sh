#!/usr/bin/env bash
# Copies the prompts from the main checkout into each agent's runtime files.
# Runs as the agents user: once from agents/setup.sh, then from ops/dispatcher.sh before every wake-up,
# so a merged prompt change reaches an agent on its next run.
#   agents/sync-prompts.sh [agent ...]      (default: all six)
#
# OpenClaw agents get AGENTS.md (team rules), SOUL.md (role) and IDENTITY.md (name and lane) in their workspace.
# Hermes agents get one SOUL.md in their profile: role first, then the team rules.
# Plain copies, not symlinks: OpenClaw refuses symlinked prompt files.
set -euo pipefail

ROOT=${ROOT:-/srv/daily-briefing}
WORK=${WORK:-/home/agents/work}
PROFILES=${PROFILES:-$HOME/.hermes/profiles}
A=$ROOT/agents

# put <dest> <source...>: write the sources into dest, only if the result differs.
put() {
  local dest=$1; shift
  local tmp
  tmp=$(mktemp "$dest.XXXX")
  {
    echo "<!-- Generated by agents/sync-prompts.sh from: ${*#"$ROOT/"}. Edit those files in the repo, not this one. -->"
    for f in "$@"; do echo; cat "$f"; done
  } > "$tmp"
  if cmp -s "$tmp" "$dest"; then rm -f "$tmp"; else mv "$tmp" "$dest"; fi
}

sync_one() {
  local agent=$1
  case $agent in
    builder-ingest|builder-web|builder-ops)
      mkdir -p "$WORK/$agent"
      put "$WORK/$agent/AGENTS.md"   "$A/WORKFLOW.md"
      put "$WORK/$agent/SOUL.md"     "$A/builder/SOUL.md"
      put "$WORK/$agent/IDENTITY.md" "$A/$agent/IDENTITY.md" ;;
    tester)
      mkdir -p "$WORK/$agent"
      put "$WORK/$agent/AGENTS.md"   "$A/WORKFLOW.md"
      put "$WORK/$agent/SOUL.md"     "$A/tester/SOUL.md"
      put "$WORK/$agent/IDENTITY.md" "$A/tester/IDENTITY.md" ;;
    orchestrator|reviewer)
      [ -d "$PROFILES/$agent" ] || { echo "no Hermes profile: $agent (run agents/setup.sh)" >&2; return 1; }
      put "$PROFILES/$agent/SOUL.md" "$A/$agent/SOUL.md" "$A/WORKFLOW.md" ;;
    *) echo "unknown agent: $agent" >&2; return 1 ;;
  esac
}

[ $# -gt 0 ] || set -- orchestrator builder-ingest builder-web builder-ops tester reviewer
for agent in "$@"; do sync_one "$agent"; done
